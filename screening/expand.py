"""Expands the advisory word list into the hashed form the ports carry.

    python screening/expand.py

Reads `screening/words.txt`, which is not in this repository and never will
be. Writes one generated source file per port, each holding the version tag
from `screening/VERSION` and the sorted hashes of every variant.

The rules are specification section 17. The expansion itself lives in
`reference/gpc2.py`, so there is one implementation of it and this script is
only plumbing.

Nothing here runs in CI, because CI has no word file. What CI checks instead is
that the four ports agree: each asserts the version, the count and the digest
recorded in `test_data/v2_screen_list.csv`, so a port whose copy drifted fails.
"""

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(REPO / "reference"))

import gpc2  # noqa: E402

WORDS = HERE / "words.txt"
VERSION = HERE / "VERSION"

